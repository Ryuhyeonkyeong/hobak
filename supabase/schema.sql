CREATE TABLE IF NOT EXISTS public.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  category TEXT NOT NULL DEFAULT '기타 중고물품',
  time_ago TEXT NOT NULL DEFAULT '방금 전',
  price INTEGER NOT NULL DEFAULT 0,
  is_free_share BOOLEAN NOT NULL DEFAULT false,
  status TEXT NOT NULL DEFAULT '판매중' CHECK (status IN ('판매중', '예약중', '판매완료')),
  hobak_pay BOOLEAN NOT NULL DEFAULT false,
  seller_nickname TEXT NOT NULL DEFAULT '호박이웃',
  seller_region TEXT NOT NULL DEFAULT '양정동',
  seller_manner_temp NUMERIC(4,1) NOT NULL DEFAULT 37.5,
  seller_avatar_emoji TEXT NOT NULL DEFAULT '🎃',
  description TEXT NOT NULL DEFAULT '',
  chats INTEGER NOT NULL DEFAULT 0,
  likes INTEGER NOT NULL DEFAULT 0,
  views INTEGER NOT NULL DEFAULT 0,
  liked BOOLEAN NOT NULL DEFAULT false,
  images JSONB NOT NULL DEFAULT '[]'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- RLS 활성화 및 공개 읽기/쓰기/수정 정책 (데모용)
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public read access on products" ON public.products;
CREATE POLICY "Allow public read access on products"
  ON public.products FOR SELECT
  USING (true);

DROP POLICY IF EXISTS "Allow public insert access on products" ON public.products;
CREATE POLICY "Allow public insert access on products"
  ON public.products FOR INSERT
  WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public update access on products" ON public.products;
CREATE POLICY "Allow public update access on products"
  ON public.products FOR UPDATE
  USING (true)
  WITH CHECK (true);

